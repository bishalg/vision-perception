/** `table` is `t.exports.errors` of the active locale (default: English, for callers outside this package). */
export function exportsErrorMessage(slug: string | null, status: number, table: Record<string, string> = errors): string {
  if (slug && table[slug]) return table[slug];
  if (status === 403) return table.forbidden!;
  if (status === 404) return table["not-found"]!;
  if (status === 429) return table["rate-limited"]!;
  if (status === 0) return table.unavailable!;
  return table.fallback!;
}

