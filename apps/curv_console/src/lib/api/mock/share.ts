/**
 * Mock share links (SHR-8, SHR-9, WP-C.19). Synthetic data only. It mimics the answers the UI surfaces (passcode
 * once, `404` unknown or revoked, `410` expired / exhausted / export gone, `401` wrong passcode); the real rules,
 * passcode hashing, rate limits and audit live in the Rust backend. No passcode is kept in clear: the mock stores a
 * marker of the seeded passcode or of the generated one only to compare, never returns it again, and never logs.
 */
import { ApiError, PROBLEM_BASE } from "../types";
import {
  SHARE_LINK_DEFAULT_DAYS,
  SHARE_LINK_DEFAULT_DOWNLOADS,
  type CreatedShareLink,
  type ShareApi,
  type ShareLink,
} from "../share";
import { MOCK_CASE_EXPORT_ID, latestMockExportStore, type MockExportStore } from "./exports";

export interface MockShareContext {
  orgId: string;
  userId: string;
  /** Epoch milliseconds (`MOCK_FIXED_NOW`). Unused: link expiry runs on the real clock (see `createMockShare`). */
  now: number;
  /** The exports the links belong to; defaults to the exports mock built last (see `latestMockExportStore`). */
  exports?: MockExportStore;
}

/** Synthetic passcode of the seeded links (mock only; real passcodes are generated by the backend and shown once). */
export const MOCK_SHARE_PASSCODE = "MOCKPASS2345";
/** Seeded links on `MOCK_CASE_EXPORT_ID`, one per state, for the public page's error paths. */
export const MOCK_SHARE_LINKS = {
  active: "5a5e0000-0000-4000-8000-000000000001",
  expired: "5a5e0000-0000-4000-8000-000000000002",
  exhausted: "5a5e0000-0000-4000-8000-000000000003",
  revoked: "5a5e0000-0000-4000-8000-000000000004",
} as const;

const PASSCODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const DAY = 86_400_000;

function problem(status: number, slug: string, title: string, detail?: string, params?: { name: string; reason: string }[]) {
  return new ApiError(status, {
    type: `${PROBLEM_BASE}${slug}`,
    title,
    status,
    detail,
    ...(params ? { invalid_params: params } : {}),
  });
}

const notFound = () => problem(404, "not-found", "Not found", "share link not found");

/** A minimal valid (empty) ZIP: the end-of-central-directory record only. Synthetic stand-in for the case package. */
const EMPTY_ZIP = new Uint8Array([0x50, 0x4b, 0x05, 0x06, ...new Array<number>(18).fill(0)]);

/** Not a real hash (the backend uses Argon2id): a fingerprint so the mock compares passcodes without keeping them as typed. */
function marker(passcode: string): string {
  let h = 2166136261;
  for (const ch of passcode) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
  return `fnv1a:${h.toString(16)}:${passcode.length}`;
}

interface Row {
  link: ShareLink;
  passcodeMarker: string;
  /** The package's file name and size when the link was made (the download route may not see the export, below). */
  fileName: string;
  bytes: number;
}

interface SharedState {
  rows: Map<string, Row>;
  /** Issued download tokens: token → link id (valid until the link stops serving). */
  tokens: Map<string, string>;
  seq: number;
}

/**
 * Links and download tokens are process-wide (on `globalThis`), not per mock client: `next dev` loads the route
 * handler `/api/share/[id]` in another module graph than the pages and server actions, so it gets its own mock client
 * (`getApi`'s singleton is per graph). Without this the token issued by the passcode step would be unknown to the
 * download route. Test files run in their own worker, so each starts from the seeds.
 */
const STATE_KEY = Symbol.for("curv-console.mock.share-links");
function sharedState(): SharedState {
  const g = globalThis as unknown as Record<symbol, SharedState | undefined>;
  return (g[STATE_KEY] ??= { rows: new Map(), tokens: new Map(), seq: 100 });
}

export function createMockShare(ctx: MockShareContext): ShareApi {
  // Real clock, like the mock TOTP: the export page shows link states against the request time, so a link's expiry
  // must be on the same clock or every seeded and new link would look expired days after MOCK_FIXED_NOW.
  const now = () => Date.now();
  const store = ctx.exports ?? latestMockExportStore();
  const iso = (offsetMs: number) => new Date(now() + offsetMs).toISOString();
  const state = sharedState();
  const { rows, tokens } = state;
  const next = () => (state.seq += 1);

  const linkUrl = (id: string) => `/share/${id}`;
  const seed = (id: string, over: Partial<ShareLink>) => {
    if (rows.has(id)) return;
    rows.set(id, {
      passcodeMarker: marker(MOCK_SHARE_PASSCODE),
      fileName: "case-package-e20c0de0.zip",
      bytes: 48_211,
      link: {
        id, export_id: MOCK_CASE_EXPORT_ID, url: linkUrl(id), created_at: iso(-DAY), expires_at: iso(2 * DAY),
        max_downloads: 5, downloads: 0, opens: 0, revoked_at: null, last_opened_at: null, ...over,
      },
    });
  };
  seed(MOCK_SHARE_LINKS.active, { downloads: 1, opens: 2, last_opened_at: iso(-3_600_000) });
  seed(MOCK_SHARE_LINKS.expired, { created_at: iso(-4 * DAY), expires_at: iso(-DAY), max_downloads: 1 });
  seed(MOCK_SHARE_LINKS.exhausted, { max_downloads: 1, downloads: 1, opens: 1, last_opened_at: iso(-7_200_000) });
  seed(MOCK_SHARE_LINKS.revoked, { revoked_at: iso(-3_600_000) });

  const snap = <T,>(v: T): T => structuredClone(v);

  function caseExport(exportId: string) {
    const e = store?.find(exportId);
    if (!e) throw problem(404, "not-found", "Not found", "Export not found");
    return e;
  }

  function newPasscode(): string {
    // Synthetic, deterministic per mock process (seq-based); the backend draws from a CSPRNG.
    let n = next() * 2654435761;
    let out = "";
    for (let i = 0; i < 12; i++) {
      out += PASSCODE_ALPHABET[n % PASSCODE_ALPHABET.length];
      n = Math.floor(n / PASSCODE_ALPHABET.length) + (i + 1) * 7919;
    }
    return out;
  }

  /** The answer for a link that can no longer serve, in the backend's order; null while it serves. */
  function refusal(row: Row | undefined): ApiError | null {
    if (!row || row.link.revoked_at) return notFound();
    if (Date.parse(row.link.expires_at) <= now()) {
      return problem(410, "share-link-expired", "Share link expired", "this share link has expired");
    }
    // Only checked where this client holds the export (see SharedState); the mock never expires one anyway.
    const e = store?.find(row.link.export_id);
    if (e?.status === "expired") return problem(410, "export-expired", "Export expired", "the shared file is no longer available");
    if ((row.link.downloads ?? 0) >= row.link.max_downloads) {
      return problem(410, "share-link-exhausted", "Share link used up", "this share link has reached its download limit");
    }
    return null;
  }

  return {
    async createShareLink(exportId, req) {
      const e = caseExport(exportId);
      if (e.format !== "case_package") throw problem(409, "conflict", "Conflict", "share links are for case packages only");
      if (e.status !== "succeeded") throw problem(409, "conflict", "Conflict", `the export is ${e.status}; nothing to share`);
      const days = req?.expires_in_days ?? SHARE_LINK_DEFAULT_DAYS;
      const downloads = req?.max_downloads ?? SHARE_LINK_DEFAULT_DOWNLOADS;
      const params: { name: string; reason: string }[] = [];
      if (days < 1 || days > 7) params.push({ name: "expires_in_days", reason: "must be 1..7" });
      if (downloads < 1 || downloads > 5) params.push({ name: "max_downloads", reason: "must be 1..5" });
      if (params.length) throw problem(400, "validation-failed", "Validation failed", undefined, params);
      const passcode = newPasscode();
      const id = `5a5e0000-0000-4000-8000-${String(next()).padStart(12, "0")}`;
      const link: ShareLink = {
        id, export_id: exportId, url: linkUrl(id), created_at: iso(0), expires_at: iso(days * DAY),
        max_downloads: downloads, downloads: 0, opens: 0, revoked_at: null, last_opened_at: null,
      };
      rows.set(id, {
        link, passcodeMarker: marker(passcode), fileName: e.file_name ?? "case-package.zip", bytes: e.byte_size ?? EMPTY_ZIP.length,
      });
      store?.update(exportId, { share_links_n: [...rows.values()].filter((r) => r.link.export_id === exportId).length });
      const created: CreatedShareLink = { link: snap(link), passcode };
      return created;
    },
    async listShareLinks(exportId) {
      caseExport(exportId);
      const items = [...rows.values()]
        .map((r) => r.link)
        .filter((l) => l.export_id === exportId)
        .sort((a, b) => b.created_at.localeCompare(a.created_at) || b.id.localeCompare(a.id));
      return { items: snap(items), next_cursor: null };
    },
    async revokeShareLink(linkId) {
      const row = rows.get(linkId);
      if (!row) throw notFound();
      row.link.revoked_at ??= iso(0);
    },
    async openShareLink(linkId, passcode) {
      const row = rows.get(linkId);
      const refused = refusal(row);
      if (refused) throw refused;
      if (marker(passcode) !== row!.passcodeMarker) {
        throw problem(401, "share-passcode-invalid", "Passcode invalid", "the passcode does not match");
      }
      const link = row!.link;
      link.opens = (link.opens ?? 0) + 1;
      link.last_opened_at = iso(0);
      const token = `mock-share-token.${next()}`;
      tokens.set(token, linkId);
      return {
        export_id: link.export_id,
        file_name: row!.fileName,
        bytes: row!.bytes,
        expires_at: link.expires_at,
        downloads_left: link.max_downloads - (link.downloads ?? 0),
        download_token: token,
      };
    },
    async mockShareFile(linkId, downloadToken) {
      if (tokens.get(downloadToken) !== linkId) {
        throw problem(401, "unauthorized", "Unauthorized", "the download token is invalid or has expired");
      }
      const row = rows.get(linkId);
      const refused = refusal(row);
      if (refused) throw refused;
      row!.link.downloads = (row!.link.downloads ?? 0) + 1;
      return new Response(EMPTY_ZIP.slice(), {
        status: 200,
        headers: {
          "Content-Type": "application/zip",
          "Content-Disposition": `attachment; filename="${row!.fileName}"`,
          "Cache-Control": "no-store",
        },
      });
    },
  };
}
