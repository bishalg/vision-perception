//! owner: WP-L.0
//!
//! `asd-cli i18n export` (I18N-6, I18N-7) through the real binary: the console module, the
//! String Catalog and the Android resources of the fixture catalogue
//! (`tests/fixtures/i18n/catalogue`) equal their goldens (`tests/fixtures/i18n/golden`).
//! Re-bless with `ASD_I18N_BLESS=1 cargo test -p asd-cli --test i18n_export`.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const FIXTURES: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/i18n");

fn cli(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_asd-cli"))
        .args(args)
        .output()
        .expect("run asd-cli")
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("asd-cli-i18n-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Compares `actual` with the golden `rel` (or rewrites it when blessing).
fn golden(actual: &Path, rel: &str) {
    let golden = Path::new(FIXTURES).join("golden").join(rel);
    let text = std::fs::read_to_string(actual).unwrap();
    if std::env::var_os("ASD_I18N_BLESS").is_some() {
        std::fs::create_dir_all(golden.parent().unwrap()).unwrap();
        std::fs::write(&golden, &text).unwrap();
    }
    let expected = std::fs::read_to_string(&golden)
        .unwrap_or_else(|e| panic!("{}: {e} (bless with ASD_I18N_BLESS=1)", golden.display()));
    assert_eq!(text, expected, "{rel} differs from its golden");
}

fn export(target: &str, out: &Path) {
    let catalogue = format!("{FIXTURES}/catalogue");
    let o = cli(&[
        "i18n",
        "export",
        "--target",
        target,
        "--out",
        out.to_str().unwrap(),
        "--catalogue",
        &catalogue,
    ]);
    assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
}

#[test]
fn console_module_equals_its_golden() {
    let dir = scratch("console");
    let out = dir.join("domain.ts");
    export("console", &out);
    golden(&out, "domain.ts");
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.starts_with("// GENERATED by asd-cli i18n export; do not edit"));
    assert!(text.contains("\"age_band.range\": { min: string | number; max: string | number };"));
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn xcstrings_equals_its_golden() {
    let dir = scratch("xcstrings");
    let out = dir.join("Domain.xcstrings");
    export("xcstrings", &out);
    golden(&out, "Domain.xcstrings");
    let v: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(&out).unwrap()).unwrap();
    let range = &v["strings"]["age_band.range"]["localizations"];
    assert_eq!(range["ne"]["stringUnit"]["value"], "%1$@–%2$@ महिना");
    assert_eq!(range["ne"]["stringUnit"]["state"], "needs_review");
    assert_eq!(range["hi"]["stringUnit"]["value"], "%1$@–%2$@ माह");
    // hi only where present.
    assert!(v["strings"]["unit.percent"]["localizations"]["hi"].is_null());
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn android_resources_equal_their_goldens() {
    let dir = scratch("android");
    export("android", &dir);
    for rel in [
        "values/domain_strings.xml",
        "values-ne/domain_strings.xml",
        "values-hi/domain_strings.xml",
    ] {
        golden(&dir.join(rel), &format!("android/{rel}"));
    }
    let ne = std::fs::read_to_string(dir.join("values-ne/domain_strings.xml")).unwrap();
    assert!(
        ne.contains("<string name=\"age_band__range\">%1$s–%2$s महिना</string>"),
        "{ne}"
    );
    assert!(ne.contains("name=\"problem__case_consent_missing\""));
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn usage_errors_exit_2() {
    assert_eq!(cli(&["i18n"]).status.code(), Some(2));
    assert_eq!(
        cli(&["i18n", "export", "--target", "console"])
            .status
            .code(),
        Some(2)
    );
    assert_eq!(
        cli(&["i18n", "export", "--target", "pdf", "--out", "/tmp/x"])
            .status
            .code(),
        Some(2)
    );
    assert_eq!(
        cli(&["i18n", "check", "--bogus", "x"]).status.code(),
        Some(2)
    );
}
